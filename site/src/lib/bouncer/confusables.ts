/*
  The confusable skeleton the reserved-name check compares on (launch
  candidate, 2026-10-22, the founder; review M1). One module, imported by
  creationPolicy.ts, which both the attestation service and the create form
  use, so the two compute the same skeleton from the same table.

  It is the Unicode TR39 skeleton (NFD, each character to its confusables.txt
  prototype, NFD again) with NFKD in place of NFD, so the compatibility forms
  fold too (fullwidth ＢＯＵＮＣＥＲ, mathematical 𝐁𝐎𝐔𝐍𝐂𝐄𝐑, circled Ⓑ, squared
  🄱, the Roman numeral Ⅽ). The table is the part of confusables.txt that ends
  in Latin (confusablesData.ts, generated by scripts/gen-confusables.ts, with
  the Unicode version and the source's sha256 in its header), and the reviewed
  supplement for the look-alikes TR39 leaves outside Latin (the small capitals
  ʙ ɴ ʀ ᴇ, negative squared 🅱, regional indicators 🇧; confusablesSupplement.ts).

  latinSkeleton(text) returns the characters as the reserved check reads them:
    - each look-alike as its Latin capitals (А → A, ʙ → B, Ж stays Ж);
    - marks dropped (after NFKD: Ö → O);
    - capitals: A to Z and digits as is, other letters upper-cased.
  What is left that is not A to Z is creationPolicy's business: it folds the
  digits, drops what is not a letter and treats any other letter as a wildcard.
  Nothing is dropped here, so an unknown letter is never silently removed.
*/
import { TR39_LATIN } from "./confusablesData";
import { SUPPLEMENT } from "./confusablesSupplement";

function decode(table: string): ReadonlyMap<string, string> {
  const map = new Map<string, string>();
  let src = "";
  let proto = "";
  for (const ch of table) {
    if (ch.codePointAt(0)! >= 0x80) {
      if (src) map.set(src, proto);
      src = ch;
      proto = "";
    } else proto += ch;
  }
  if (src) map.set(src, proto);
  return map;
}
const TR39 = decode(TR39_LATIN);

/* One character's Latin reading, or null. TR39 first, then the supplement, then the same for the character's other case (a lower-case form of a listed capital reads the same). */
export function latinOf(ch: string): string | null {
  const direct = TR39.get(ch) ?? SUPPLEMENT[ch];
  if (direct !== undefined) return direct;
  for (const other of [ch.toUpperCase(), ch.toLowerCase()]) {
    if (other === ch || [...other].length !== 1) continue;
    const v = TR39.get(other) ?? SUPPLEMENT[other];
    if (v !== undefined) return v;
  }
  return null;
}

export function latinSkeleton(text: string): string {
  const first = text.normalize("NFKD");
  const mapped = Array.from(first, (ch) => (ch.codePointAt(0)! < 0x80 ? ch : (latinOf(ch) ?? ch))).join("");
  return mapped.normalize("NFKD").replace(/\p{M}+/gu, "").toUpperCase().normalize("NFKD").replace(/\p{M}+/gu, "");
}

/* For the check and the review: how many TR39 entries the table carries. */
export const TR39_ENTRIES = TR39.size;
